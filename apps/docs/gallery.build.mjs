#!/usr/bin/env node
// Generates apps/docs/components.data.js from registry/registry.json, and
// refreshes the no-JS link list inside components.html between its markers.
//
//   node apps/docs/gallery.build.mjs             write both files
//   node apps/docs/gallery.build.mjs --check     fail if either is stale
//
// Pure work (registry -> groups and cards) lives in gallery.core.js so it can
// be unit-tested without touching disk; this script is the thin, side-effecting
// edge: read the registry, ask the filesystem which demo files exist, write.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { buildGallery } from './gallery.core.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../..');
const REGISTRY = join(ROOT, 'registry', 'registry.json');
const DATA_OUT = join(HERE, 'components.data.js');
const HTML_OUT = join(HERE, 'components.html');
const NOSCRIPT_START = '<!-- gallery:noscript:start -->';
const NOSCRIPT_END = '<!-- gallery:noscript:end -->';

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function renderNoscript(groups) {
  if (!groups.length) return '<p class="note">No components yet.</p>';
  const lines = groups.map(g => {
    const items = g.items
      .filter(c => c.demoUrl)
      .map(c => `        <li><a href="${esc(c.demoUrl)}">${esc(c.title)}</a></li>`)
      .join('\n');
    if (!items) return '';
    return `      <li>\n        <h3>${esc(g.title)}</h3>\n        <ul>\n${items}\n        </ul>\n      </li>`;
  }).filter(Boolean);
  return `<p class="note">The live previews need JavaScript. Every item that has one still links to its demo page:</p>\n    <ul class="ns-groups">\n${lines.join('\n')}\n    </ul>`;
}

export async function generate({ root = ROOT } = {}) {
  const index = JSON.parse(readFileSync(join(root, 'registry', 'registry.json'), 'utf8'));
  const fileExists = p => existsSync(join(root, p));
  // Which scenes actually appear as a plate on the front door, so a scene
  // with no demo.html of its own (only paus and rampon, today) gets a link
  // there only when there is really something at the other end of it.
  let plated = [];
  try {
    ({ order: plated } = await import(pathToFileURL(join(HERE, 'manifest.js')).href));
  } catch { /* apps/docs/manifest.js should always exist; leave the list empty if it somehow doesn't */ }
  const isPlated = name => plated.includes(name);
  const { groups, count } = buildGallery(index, fileExists, isPlated);

  const banner = '// Generated by `node apps/docs/gallery.build.mjs` from registry/registry.json. Do not edit by hand.\n';
  const dataText = `${banner}export const gallery = ${JSON.stringify({ groups, count }, null, 2)};\n`;

  const htmlSrc = readFileSync(HTML_OUT, 'utf8');
  const startAt = htmlSrc.indexOf(NOSCRIPT_START);
  const endAt = htmlSrc.indexOf(NOSCRIPT_END);
  if (startAt === -1 || endAt === -1 || endAt < startAt) {
    throw new Error(`components.html is missing the ${NOSCRIPT_START} / ${NOSCRIPT_END} markers`);
  }
  const htmlText = htmlSrc.slice(0, startAt + NOSCRIPT_START.length)
    + '\n    ' + renderNoscript(groups) + '\n    '
    + htmlSrc.slice(endAt);

  // Everything this page links to must be a portable web path: root-absolute
  // for the registry tree (works unchanged in dev and once deployed), or a
  // same-directory relative link for another apps/docs page (index.html and
  // components.html are always siblings, but a root-absolute /index.html
  // would only be right once the site build promotes apps/docs/* to the
  // site's own root, and 404s in dev). Never a Windows drive letter or a
  // backslash, which would only work on this one box.
  const problems = [];
  for (const g of groups) for (const c of g.items) {
    for (const [field, url] of [['demoUrl', c.demoUrl], ['docsUrl', c.docsUrl], ['promptUrl', c.promptUrl]]) {
      if (url == null) continue;
      if (!(url.startsWith('/') || url.startsWith('./')) || url.includes('\\') || /^[a-zA-Z]:/.test(url)) {
        problems.push(`${c.name}.${field} = ${url}`);
      }
    }
  }
  if (problems.length) {
    throw new Error(`gallery data holds a local or non-portable path:\n  ${problems.join('\n  ')}`);
  }

  return { dataText, htmlText, count, groups };
}

async function main(argv) {
  const check = argv.includes('--check');
  const { dataText, htmlText, count } = await generate({});

  const currentData = existsSync(DATA_OUT) ? readFileSync(DATA_OUT, 'utf8').replace(/\r\n/g, '\n') : null;
  const currentHtml = readFileSync(HTML_OUT, 'utf8').replace(/\r\n/g, '\n');
  const dataStale = currentData !== dataText;
  const htmlStale = currentHtml !== htmlText;

  if (check) {
    if (dataStale || htmlStale) {
      if (dataStale) console.error('apps/docs/components.data.js is out of date with registry/registry.json.');
      if (htmlStale) console.error('apps/docs/components.html\'s no-JS link list is out of date.');
      console.error('Run node apps/docs/gallery.build.mjs to refresh it.');
      return 1;
    }
    console.log(`apps/docs/components.data.js and its no-JS links are up to date with ${count} item(s).`);
    return 0;
  }

  writeFileSync(DATA_OUT, dataText);
  if (htmlStale) writeFileSync(HTML_OUT, htmlText);
  console.log(`Wrote apps/docs/components.data.js: ${count} item(s).${htmlStale ? ' Refreshed the no-JS links in components.html.' : ''}`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main(process.argv.slice(2));
}
