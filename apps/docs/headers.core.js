// The _headers file's pure core: the text, from no disk state. build.mjs
// writes it; headers.core.test.js holds the CSP string byte for byte so a
// future edit cannot loosen the site's security headers by accident, and
// pins the two cross-origin rules that let another site load a scene or the
// registry from here (docs/requests/2026-10-03-open-atelier.md).
//
// The CSP keeps 'unsafe-inline' for scripts and styles on purpose: see the
// comment in build.mjs (workerd truncates _headers values at about 2 KB, and
// a hash-strict policy needs 4.7 KB). This module only carries the string.

const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:", // inline SVG marks load from CSS as data:, the veranda's canvas hands its picture over as a blob:
  "font-src 'self'",
  "media-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'", // no page of this site is somebody else's iframe
].join('; ');

/** The exact Content-Security-Policy the site has always served. */
export const CSP = csp;

/** Every path prefix that answers other origins (a scene module, the registry over HTTP). */
export const CROSS_ORIGIN_PREFIXES = ['/packages/', '/registry/'];

export function headersText() {
  return `# Generated by apps/docs/build.mjs. Do not edit by hand.
# Rules merge: a path matching two rules gets both headers, so the general
# block sets no Cache-Control and the immutable rules below stand alone
# (Workers assets already answer with max-age=0, must-revalidate by default).
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()

/packages/*
  Access-Control-Allow-Origin: *

/registry/*
  Access-Control-Allow-Origin: *

/packages/tokens/fonts/*
  Cache-Control: public, max-age=31536000, immutable

/posters/*
  Cache-Control: public, max-age=31536000, immutable
`;
}
